def get_type(type_id: str) -> Optional[DiagramType]:
    """Retrieve diagram type by id (case-insensitive and hyphen-tolerant)."""
    normalized = type_id.strip().lower().replace("_", "-")
    return DIAGRAM_TYPES.get(normalized)


def list_types(category: Optional[str] = None) -> List[DiagramType]:
    """List diagram types, optionally filtered by category."""
    if category:
        return [t for t in DIAGRAM_TYPES.values() if t.category.lower() == category.lower()]
    return list(DIAGRAM_TYPES.values())
